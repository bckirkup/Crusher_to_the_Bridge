class MaterializationError(Exception):
    """Typed materialization failure carried into the COMMIT status."""

    def __init__(self, kind: str, detail: str):
        super().__init__(f"{kind}: {detail}")
        self.kind = kind
        self.detail = detail


class LedgerBoundBudget(ReadBudget):
    """ReadBudget mirrored onto the shared reservation ledger.

    Every ranged GET/HEAD the pinned reader charges here additionally
    charges ``max_api_calls_total``/``max_get_requests`` and
    ``max_compressed_bytes_read`` on the ledger — retries included,
    because the reader charges them through the same methods.
    """

    def __init__(self, ledger: BudgetLedger, **kwargs):
        super().__init__(**kwargs)
        self._ledger = ledger

    def charge_request(self, detail: str = "") -> None:
        super().charge_request(detail)
        self._ledger.charge("max_api_calls_total", 1, detail)
        self._ledger.charge("max_get_requests", 1, detail)

    def charge_bytes(self, n: int, detail: str = "") -> None:
        super().charge_bytes(n, detail)
        self._ledger.charge("max_compressed_bytes_read", n, detail)


@dataclass
class MaterializeSpec:
    """The materialize-phase request document (offline form).

    ``extraction_profile`` names a declared extraction profile (e.g.
    ``first_paper_scalar``); ``suppress_tables`` drops base/derived
    tables before their rows are built and is unioned with the profile's
    own suppressions at construction.
    """

    sources: list[SourceSpec]
    ctx: ReductionContext
    shard_size: int = 64
    requested_tables: tuple[str, ...] = ()
    metric_bindings: dict = field(default_factory=dict)
    declared_source_count: int | None = None
    partition_format: str = "jsonl"  # "jsonl" | "parquet"
    distribution_dims: tuple[str, ...] = ("campaign_id", "vessel_id")
    utc: str = ""
    extraction_profile: str | None = None
    suppress_tables: frozenset[str] = frozenset()

    def __post_init__(self) -> None:
        if self.extraction_profile == first_paper.PROFILE_ID:
            self.suppress_tables = frozenset(
                set(self.suppress_tables)
                | set(first_paper.defaults()["suppress_tables"])
            )


@dataclass
class MaterializationResult:
    status: str
    snapshot_id: str | None
    commit_key: str | None
    manifest: list[dict]
    table_counts: dict[str, int]
    errors: list[dict]
    checkpoint_uri: str | None
    completed_shards: list[int]


def _attempt_prefix(ctx: ReductionContext) -> str:
    return f"{DERIVED_ROOT}/attempts/{ctx.reduction_id}"


def _encode_rows(rows: list[dict], fmt: str) -> bytes:
    ordered = sorted(rows, key=lambda r: canonical_json(r))
    if fmt == "jsonl":
        return b"".join(
            (canonical_json(r) + "\n").encode() for r in ordered
        )
    if fmt == "parquet":
        return _encode_parquet(ordered)
    raise MaterializationError("unsupported_format", fmt)


def _encode_parquet(rows: list[dict]) -> bytes:
    import pyarrow as pa
    import pyarrow.parquet as pq

    cols: dict[str, list] = {}
    for row in rows:
        for k in row:
            cols.setdefault(k, [])
    for row in rows:
        for k in cols:
            v = row.get(k)
            cols[k].append(
                json.dumps(v, sort_keys=True, default=str)
                if isinstance(v, (dict, list))
                else v
            )
    arrays = {k: pa.array(v) for k, v in sorted(cols.items())}
    buf = io.BytesIO()
    pq.write_table(pa.table(arrays), buf)
    return buf.getvalue()


def decode_rows(data: bytes, fmt: str) -> list[dict]:
    if fmt == "jsonl":
        return [json.loads(line) for line in data.splitlines() if line.strip()]
    if fmt == "parquet":
        import pyarrow.parquet as pq

        return pq.ParquetFile(io.BytesIO(data)).read().to_pylist()
    raise MaterializationError("unsupported_format", fmt)


def _ext(fmt: str) -> str:
    return {"jsonl": "jsonl", "parquet": "parquet"}[fmt]


def _min_max_key(rows: list[dict]) -> tuple[Any, Any]:
    if not rows:
        return None, None
    keys = [r.get("row_id") for r in rows]
    return min(keys), max(keys)


class _ShardAccumulator:
    """Per-source tallies feeding coverage_cells + distributions.

    ``mark``/``delta_since`` produce the per-shard delta persisted in the
    checkpoint document; ``apply_delta`` folds a stored delta back in on
    resume (issue #1116). ``metric_values`` is intentionally excluded
    from the delta — it is rebuilt from the durable ``runs``/
    ``run_scalars`` partitions instead of being checkpointed.
    """

    def __init__(self, spec: MaterializeSpec) -> None:
        self.spec = spec
        self.cells: dict[tuple, dict] = {}
        self.metric_values: dict[str, dict[str, list]] = {}
        self.run_meta: dict[str, dict] = {}
        self.selected_runs: set[str] = set()
        self.errors: list[dict] = []
        self.oversized_rows = 0
        self.schema_or_corruption = False
        self.unsupported_family = False
        self.resource_stops = 0
        self.scan_index: dict[str, dict] = {}
        self.scan_conflicts: list[dict] = []

    def mark(self) -> dict:
        """Snapshot cheap state so ``delta_since`` can diff this shard."""
        return {
            "cells": {k: json.loads(canonical_json(v))
                      for k, v in self.cells.items()},
            "selected": set(self.selected_runs),
            "run_meta": set(self.run_meta),
            "n_errors": len(self.errors),
            "oversized_rows": self.oversized_rows,
            "schema_or_corruption": self.schema_or_corruption,
            "unsupported_family": self.unsupported_family,
            "resource_stops": self.resource_stops,
            "scan_keys": set(self.scan_index),
            "n_scan_conflicts": len(self.scan_conflicts),
        }

    def delta_since(self, mark: dict) -> dict:
        """JSON-safe accumulator delta for one shard's checkpoint."""
        return {
            "cells": {
                json.dumps(list(k)): self.cells[k]
                for k in self.cells
                if mark["cells"].get(k) != self.cells[k]
            },
            "selected_runs": sorted(self.selected_runs - mark["selected"]),
            "run_meta": {
                u: self.run_meta[u]
                for u in self.run_meta.keys() - mark["run_meta"]
            },
            "errors": self.errors[mark["n_errors"]:],
            "oversized_rows": self.oversized_rows,
            "schema_or_corruption": self.schema_or_corruption,
            "unsupported_family": self.unsupported_family,
            "resource_stops": self.resource_stops,
            "scan_index": {
                k: self.scan_index[k]
                for k in self.scan_index.keys() - mark["scan_keys"]
            },
            "scan_conflicts": self.scan_conflicts[mark["n_scan_conflicts"]:],
            "metric_bindings": self.spec.metric_bindings,
        }

    def apply_delta(self, delta: dict) -> None:
        """Fold one stored shard delta back into the live accumulator."""
        for key_json, cell in (delta.get("cells") or {}).items():
            self.cells[tuple(json.loads(key_json))] = cell
        self.selected_runs.update(delta.get("selected_runs") or [])
        self.run_meta.update(delta.get("run_meta") or {})
        self.errors.extend(delta.get("errors") or [])
        self.oversized_rows = delta.get(
            "oversized_rows", self.oversized_rows)
        self.schema_or_corruption = bool(
            delta.get("schema_or_corruption", self.schema_or_corruption))
        self.unsupported_family = bool(
            delta.get("unsupported_family", self.unsupported_family))
        self.resource_stops = delta.get(
            "resource_stops", self.resource_stops)
        self.scan_index.update(delta.get("scan_index") or {})
        self.scan_conflicts.extend(delta.get("scan_conflicts") or [])

    def cell(self, spec: SourceSpec) -> dict:
        key = (
            spec.scope_id or spec.campaign_id,
            spec.campaign_id,
            spec.stage_id,
            spec.attempt_id,
            spec.cell_id,
        )
        return self.cells.setdefault(
            key,
            {
                "declared_runs": spec.declared_runs,
                "landed": 0,
                "indexed": 0,
                "parsed": 0,
                "duplicates": 0,
                "conflicts": 0,
                "selected": 0,
                "missing": 0,
                "gaps": 0,
                "unsupported": False,
                "blocked": False,
                "evidence": {},
            },
        )


def _checkpoint_key(ctx: ReductionContext, shard_idx: int) -> str:
    return (
        f"{_attempt_prefix(ctx)}/{CHECKPOINT_PREFIX}shard-{shard_idx:05d}.json"
    )


def _load_resume(store, spec: MaterializeSpec) -> dict:
    """Latest checkpoint state: completed shards, manifest, ledger spend,
    and the per-shard accumulator deltas (issue #1116)."""
    prefix = f"{_attempt_prefix(spec.ctx)}/{CHECKPOINT_PREFIX}"
    keys = [k for k in store.list(prefix) if k.endswith(".json")]
    state = {"completed": set(), "manifest": [], "spent": {},
             "acc_deltas": [], "last_checkpoint_bytes": 0}
    for key in keys:
        try:
            raw = store.get(key)
            doc = json.loads(raw)
        except (DerivedStoreError, json.JSONDecodeError):
            continue
        state["completed"].add(doc.get("shard"))
        state["manifest"].extend(doc.get("manifest_delta", []))
        state["spent"] = doc.get("ledger_spent", state["spent"])
        state["last_checkpoint_bytes"] = len(raw)
        delta = doc.get("accumulator_delta")
        if isinstance(delta, dict):
            state["acc_deltas"].append((doc.get("shard"), delta))
    return state


def _shard_tables(
    spec: MaterializeSpec,
    transport,
    store,
    ledger: BudgetLedger,
    shard: list[SourceSpec],
    acc: _ShardAccumulator,
) -> dict[str, list[dict]]:
    tables: dict[str, list[dict]] = {}
    for src in shard:
        ledger.charge("max_head_requests", 1, src.uri)
        ledger.charge("max_source_objects", 1, src.uri)
        budget = LedgerBoundBudget(ledger)
        try:
            result = reduce_source(src.family, src.to_ref(), transport, budget)
        except _ReadBudgetExceeded as exc:
            raise BudgetExceeded("read_budget", 1, 0) from exc
        for ddoc in result.docs:
            ledger.charge(
                "max_uncompressed_bytes",
                len(canonical_json(ddoc.doc).encode()),
                src.uri,
            )
        _absorb(spec, src, result, tables, acc, ledger)
    for table in spec.suppress_tables:
        tables.pop(table, None)
    return tables


def _absorb(
    spec: MaterializeSpec,
    src: SourceSpec,
    result,
    tables: dict,
    acc: _ShardAccumulator,
    ledger: BudgetLedger,
) -> None:
    cell = acc.cell(src)
    cell["landed"] += 1
    for state in {link.read_state for link in result.links}:
        if state in ("unsupported_schema", "unsupported_compression",
                     "corrupt_archive", "crc_failure", "decode_failure"):
            acc.schema_or_corruption = True
            cell["unsupported"] = True
        if state in ("resource_limit",):
            acc.resource_stops += 1
        if state in ("missing_object", "access_denied",
                     "archived_unrestored"):
            cell["blocked"] = True
    if src.family == "unknown_legacy":
        acc.unsupported_family = True
        cell["unsupported"] = True
    cell["indexed"] += len(result.assets)
    cell["gaps"] += len(result.gaps)
    cell["duplicates"] += sum(
        1 for g in result.gaps if g.reason == "duplicate_members"
    )
    if src.source_role == first_paper.SCAN_ROLE:
        _absorb_scan_role(spec, src, result, tables, acc)
        return
    cell["parsed"] += len(result.runs)
    seen: set[str] = set()
    for r in result.runs:
        if r.run_uid in seen:
            cell["conflicts"] += 1
        seen.add(r.run_uid)
        if r.selection_state == "selected":
            cell["selected"] += 1
            acc.selected_runs.add(r.run_uid)
    merge_tables(
        tables,
        emit_source_rows(
            result, src, spec.ctx, suppress=spec.suppress_tables),
    )
    merge_tables(
        tables,
        emit_long_tables(
            result, src, spec.ctx, spec.requested_tables, spec.metric_bindings
        ),
    )
    for r in result.runs:
        acc.run_meta[r.run_uid] = {
            "campaign_id": r.campaign_id,
            "vessel_id": r.hull_id,
        }
    if "distributions" not in spec.suppress_tables:
        _accumulate_metrics(acc, src, result)
    if spec.extraction_profile == first_paper.PROFILE_ID:
        merge_tables(
            tables,
            {first_paper.profile()["table_name"]: first_paper.vector_rows(
                spec, src, result, spec.ctx, acc)},
        )


def _absorb_scan_role(
    spec: MaterializeSpec,
    src: SourceSpec,
    result,
    tables: dict,
    acc: _ShardAccumulator,
) -> None:
    """Scan-row source: index its per-line docs for the profile join.

    A scan file is not an execution — it contributes no ``runs`` row and
    no parsed/selected counts, but its object/asset/gap provenance is
    recorded like any source.
    """
    first_paper.absorb_scan_rows(acc, src, result)
    emitted = emit_source_rows(
        result, src, spec.ctx, suppress=spec.suppress_tables)
    emitted.pop("runs", None)
    emitted.pop("run_scalars", None)
    merge_tables(tables, emitted)


def _accumulate_metrics(acc: _ShardAccumulator, src: SourceSpec, result) -> None:
    run_by_uid = {r.run_uid: r for r in result.runs}
    for s in result.scalars:
        run = run_by_uid.get(s.run_uid)
        group = group_key_for_run(
            {
                "campaign_id": getattr(run, "campaign_id", src.campaign_id),
                "vessel_id": getattr(run, "hull_id", src.hull_id),
            },
            acc.spec.distribution_dims,
        )
        value = s.value if isinstance(s.value, (int, float)) else None
        acc.metric_values.setdefault(group, {}).setdefault(
            s.metric_id, []
        ).append((s.run_uid, value))


def _write_shard_partitions(
    spec: MaterializeSpec,
    store,
    tables: dict[str, list[dict]],
    shard_name: str,
    ledger: BudgetLedger | None = None,
) -> list[dict]:
    """Write one shard's per-table partitions create-only.

    A row over ``_MAX_ROW_BYTES`` is not emitted: it becomes an
    ``_oversized_row`` entry the COMMIT disqualifier path counts — the
    row is never silently truncated and never blocks the shard.
    """
    entries = []
    ext = _ext(spec.partition_format)
    for table in sorted(tables):
        rows = []
        for r in tables[table]:
            if r is None:
                continue
            if len(canonical_json(r).encode()) > _MAX_ROW_BYTES:
                entries.append(_oversized_marker(table, r))
                continue
            rows.append(r)
        body = _encode_rows(rows, ext)
        uri = (
            f"{_attempt_prefix(spec.ctx)}/{SHARD_PREFIX}"
            f"{shard_name}/{table}.{ext}"
        )
        wrote = store.put_idempotent(uri, body)
        entries.append(
            {
                "partition_id": f"{shard_name}/{table}",
                "table_name": table,
                "uri": uri,
                "sha256": sha256_hex(body),
                "rows": len(rows),
                "bytes_stored": len(body),
                "min_key": _min_max_key(rows)[0],
                "max_key": _min_max_key(rows)[1],
                "statistics": None,
                "written": wrote,
            }
        )
    return entries


def _oversized_marker(table: str, row: dict) -> dict:
    """Marker for a dropped oversized row.

    ``run_scalars`` markers additionally carry the fields the resume
    metric rebuild needs (the scalar's value still counted in-memory
    when the row itself was too large to partition, so the rebuild must
    see it — bounded to a small token).
    """
    marker = {"_oversized_row": table, "row_id": row.get("row_id")}
    if table == "run_scalars":
        value_json = row.get("native_value_json")
        marker.update({
            "run_uid": row.get("run_uid"),
            "native_path": row.get("native_path"),
            "native_type": row.get("native_type"),
            "native_value_json": (
                value_json
                if isinstance(value_json, str) and len(value_json) <= 512
                else None
            ),
        })
    return marker


def _write_checkpoint(
    spec: MaterializeSpec,
    store,
    ledger: BudgetLedger,
    shard_idx: int,
    manifest_delta: list[dict],
    acc_delta: dict,
) -> str:
    doc = {
        "reduction_id": spec.ctx.reduction_id,
        "shard": shard_idx,
        "shard_count": None,
        "manifest_delta": manifest_delta,
        "accumulator_delta": acc_delta,
        "ledger_spent": ledger.snapshot(),
        "table_counts_delta": {
            e["table_name"]: e["rows"]
            for e in manifest_delta
            if "table_name" in e
        },
        "utc": spec.utc,
    }
    body = json.dumps(doc, sort_keys=True, indent=2).encode()
    key = _checkpoint_key(spec.ctx, shard_idx)
    store.put_idempotent(key, body)
    ledger.charge_checkpoint("checkpoint_reserve_bytes", len(body))
    return key


def _disqualifiers(acc: _ShardAccumulator, spec: MaterializeSpec) -> list[str]:
    out = []
    if acc.oversized_rows:
        out.append("oversized_row")
    if acc.schema_or_corruption:
        out.append("schema_or_corruption")
    if acc.unsupported_family:
        out.append("unsupported_family")
    if (
        spec.declared_source_count is not None
        and len(spec.sources) < spec.declared_source_count
    ):
        out.append("incomplete_inventory")
    if acc.errors:
        out.append("errors")
    if any(c["gaps"] for c in acc.cells.values()):
        out.append("coverage_gaps")
    return out


def _commit_status(acc: _ShardAccumulator, spec: MaterializeSpec) -> str:
    if acc.schema_or_corruption or acc.unsupported_family:
        return "quarantined"
    if _disqualifiers(acc, spec):
        return "partial"
    return "completed"


def run_materialization(
    spec: MaterializeSpec,
    transport,
    store,
    ledger: BudgetLedger,
    *,
    resume: bool = True,
    on_shard: Callable[[str, int], None] | None = None,
) -> MaterializationResult:
    """Drive the materialize phase over ``spec.sources``.

    ``on_shard(event, idx)`` fires after a shard's partitions are written
    (``"partition_written"``) and after its checkpoint is written
    (``"checkpoint_written"``) — the kill/resume test seam.
    """
    acc = _ShardAccumulator(spec)
    sources = _ordered_sources(spec)
    shards = [
        sources[i : i + spec.shard_size]
        for i in range(0, len(sources), spec.shard_size)
    ]
    manifest: list[dict] = []
    completed: set[int] = set()
    checkpoint_uri = None
    # Stopped attempts are terminal: a budget_stopped/blocked/partial
    # COMMIT is not resumable (re-finalize would DerivedConflict on the
    # create-only COMMIT). A new attempt must be approved under a fresh
    # reduction_id; the prior COMMIT carries the lineage.
    commit_key0 = f"{_attempt_prefix(spec.ctx)}/{COMMIT_NAME}"
    try:
        prior = json.loads(store.get(commit_key0).decode())
    except DerivedStoreError:
        prior = None
    if prior and prior.get("status") not in (None, "completed"):
        acc.errors.append(
            {
                "kind": "attempt_terminal",
                "detail": (
                    "attempt %s already finalized with status %s; "
                    "create a new approved child attempt"
                    % (spec.ctx.reduction_id, prior.get("status"))
                ),
                "prior_snapshot": prior.get("catalog_snapshot_id"),
                "prior_status": prior.get("status"),
            }
        )
        return MaterializationResult(
            status="blocked",
            snapshot_id=prior.get("catalog_snapshot_id") or "",
            commit_key=commit_key0,
            manifest=prior.get("partitions") or [],
            table_counts=prior.get("counts") or {},
            errors=acc.errors,
            checkpoint_uri=None,
            completed_shards=[],
        )
    if resume:
        completed, manifest, checkpoint_uri = _restore_state(
            store, spec, ledger, acc
        )
        _rebuild_from_partitions(store, spec, acc, completed)
    try:
        for idx, shard in enumerate(shards):
            if idx in completed:
                continue
            checkpoint_uri = _process_shard(
                spec, transport, store, ledger, acc,
                manifest, completed, idx, shard, on_shard,
            )
        if on_shard:
            on_shard("pre_commit", len(shards))
    except BudgetExceeded as exc:
        acc.errors.append({"kind": "budget_stopped", "detail": str(exc)})
        return _finalize(
            spec, store, ledger, acc, manifest, completed,
            checkpoint_uri, forced_status="budget_stopped",
        )
    status = _commit_status(acc, spec)
    return _finalize(
        spec, store, ledger, acc, manifest, completed,
        checkpoint_uri, forced_status=status,
    )


def _ordered_sources(spec: MaterializeSpec) -> list[SourceSpec]:
    """Deterministic source order; scan-role sources first in profiles.

    Scan-row sources must be absorbed before the run sources that join
    on them, so profile mode orders them ahead of every other URI.
    """
    if spec.extraction_profile:
        return sorted(
            spec.sources,
            key=lambda s: (
                0 if s.source_role == first_paper.SCAN_ROLE else 1,
                s.uri,
                s.source_id,
            ),
        )
    return sorted(spec.sources, key=lambda s: (s.uri, s.source_id))


def _restore_state(store, spec, ledger, acc):
    """Reload completed-shard/manifest/ledger-spend/accumulator state."""
    state = _load_resume(store, spec)
    completed = {s for s in state["completed"] if s is not None}
    manifest = list(state["manifest"])
    spent = state["spent"] or {}
    if isinstance(spent, dict):
        ledger.spent.update(spent.get("spent") or {})
        ledger.jobs = int(spent.get("jobs") or ledger.jobs)
        ledger.retries = int(spent.get("retries") or ledger.retries)
        # A checkpoint's own checkpoint_reserve_bytes charge lands after
        # its ledger_spent snapshot (see _write_checkpoint), so the
        # stored spend is missing exactly the last doc's byte length.
        ledger.spent["checkpoint_reserve_bytes"] = (
            ledger.spent.get("checkpoint_reserve_bytes", 0.0)
            + state["last_checkpoint_bytes"]
        )
    for _shard, delta in sorted(
        state["acc_deltas"], key=lambda item: item[0]
    ):
        acc.apply_delta(delta)
    checkpoint_uri = (
        f"{_attempt_prefix(spec.ctx)}/{CHECKPOINT_PREFIX}"
        f"shard-{max(completed):05d}.json"
        if completed
        else None
    )
    return completed, manifest, checkpoint_uri


def _rebuild_from_partitions(store, spec, acc, completed) -> None:
    """Rebuild ``metric_values``/run metadata from durable partitions.

    The completed shards' ``runs`` and ``run_scalars`` partitions are
    the truth already written: re-reading them restores the large
    accumulator state without checkpointing it (issue #1116).
    ``distribution_rows`` is order-insensitive over the (run, value)
    lists, so the re-derived distributions are byte-identical.
    """
    if not completed or "distributions" in spec.suppress_tables:
        return
    uid_source = _rebuild_run_state(store, spec, acc, completed)
    specs_by_id = {s.source_id: s for s in spec.sources}
    ext = _ext(spec.partition_format)
    for idx in sorted(completed):
        key = (
            f"{_attempt_prefix(spec.ctx)}/{SHARD_PREFIX}"
            f"shard-{idx:05d}/run_scalars.{ext}"
        )
        try:
            rows = decode_rows(store.get(key), spec.partition_format)
        except DerivedStoreError:
            continue
        for row in rows:
            _rebuild_scalar(spec, acc, uid_source, specs_by_id, row)


def _rebuild_run_state(store, spec, acc, completed) -> dict:
    """Read ``runs`` partitions: uid→source_id map + run_meta/selected."""
    uid_source: dict[str, str] = {}
    ext = _ext(spec.partition_format)
    for idx in sorted(completed):
        key = (
            f"{_attempt_prefix(spec.ctx)}/{SHARD_PREFIX}"
            f"shard-{idx:05d}/runs.{ext}"
        )
        try:
            rows = decode_rows(store.get(key), spec.partition_format)
        except DerivedStoreError:
            continue
        for row in rows:
            if "_oversized_row" in row:
                continue
            uid = row.get("run_uid")
            if not uid:
                continue
            uid_source[uid] = (
                (row.get("metadata_json") or {}).get("source_id"))
            acc.run_meta.setdefault(uid, {
                "campaign_id": row.get("campaign_id"),
                "vessel_id": row.get("vessel_id"),
            })
            if row.get("selection_state") == "selected":
                acc.selected_runs.add(uid)
    return uid_source


def _metric_prefix_for(src) -> str:
    if src is None:
        return "unknown_family"
    if src.uri.endswith(".parquet"):
        return "parquet_sidecar"
    return src.family


def _rebuild_scalar(spec, acc, uid_source, specs_by_id, row) -> None:
    """Fold one partitioned scalar row back into ``metric_values``."""
    uid = row.get("run_uid")
    native_path = row.get("native_path")
    if not uid or not native_path:
        return
    src = specs_by_id.get(uid_source.get(uid))
    if src is None:
        acc.errors.append({
            "kind": "metric_rebuild_orphan",
            "detail": f"run_uid {uid} has no run/source mapping",
        })
        return
    metric_id = "{}.{}".format(
        _metric_prefix_for(src),
        ".".join(
            part.replace("~1", "/").replace("~0", "~")
            for part in native_path.strip("/").split("/")
        ),
    )
    value = None
    if row.get("native_type") in ("number", "boolean"):
        raw = row.get("native_value_json")
        if raw is not None:
            try:
                value = json.loads(raw)
            except json.JSONDecodeError:
                value = None
    value = value if isinstance(value, (int, float)) else None
    meta = acc.run_meta.get(uid) or {
        "campaign_id": src.campaign_id,
        "vessel_id": src.hull_id,
    }
    group = group_key_for_run(meta, spec.distribution_dims)
    acc.metric_values.setdefault(group, {}).setdefault(
        metric_id, []
    ).append((uid, value))


def _process_shard(
    spec, transport, store, ledger, acc,
    manifest, completed, idx, shard, on_shard,
) -> str:
    """Materialize one shard: partitions, checkpoint, manifest entries."""
    mark = acc.mark()
    tables = _shard_tables(spec, transport, store, ledger, shard, acc)
    entries = _write_shard_partitions(
        spec, store, tables, f"shard-{idx:05d}"
    )
    for e in entries:
        if "_oversized_row" in e:
            acc.oversized_rows += 1
            continue
        manifest.append(e)
        ledger.charge("max_output_bytes", e["bytes_stored"], e["uri"])
    if on_shard:
        on_shard("partition_written", idx)
    checkpoint_uri = _write_checkpoint(
        spec, store, ledger, idx, entries, acc.delta_since(mark)
    )
    completed.add(idx)
    if on_shard:
        on_shard("checkpoint_written", idx)
    return checkpoint_uri


def _finalize(
    spec: MaterializeSpec,
    store,
    ledger: BudgetLedger,
    acc: _ShardAccumulator,
    manifest: list[dict],
    completed: set[int],
    checkpoint_uri: str | None,
    forced_status: str,
) -> MaterializationResult:
    derived_tables = _derived_rows(spec, acc, manifest, forced_status)
    entries = _write_shard_partitions(spec, store, derived_tables, "derived")
    manifest.extend(e for e in entries if "table_name" in e)
    counts: dict[str, int] = {}
    for e in manifest:
        if "table_name" in e:
            counts[e["table_name"]] = counts.get(e["table_name"], 0) + e["rows"]
    coverage = {
        "cells": len(acc.cells),
        "selected_unique_runs": len(acc.selected_runs),
        "scan_join_conflicts": len(acc.scan_conflicts),
        "disqualifiers": _disqualifiers(acc, spec),
    }
    snapshot_id = f"snap-{sha256_hex(canonical_json(manifest).encode())[:16]}"
    commit_key = f"{_attempt_prefix(spec.ctx)}/{COMMIT_NAME}"
    commit = {
        "catalog_snapshot_id": snapshot_id,
        "reduction_id": spec.ctx.reduction_id,
        "phase": spec.ctx.phase,
        "status": forced_status,
        "coverage": coverage,
        "errors": acc.errors,
        "lineage": {
            "request_sha256": spec.ctx.request_sha256,
            "inventory_sha256": spec.ctx.inventory_sha256,
            "implementation_sha": spec.ctx.implementation_sha,
            "image_digest": spec.ctx.image_digest,
            "adapter_registry_sha256": spec.ctx.adapter_registry_sha256,
            "fingerprint": spec.ctx.fingerprint,
        },
        "partitions": manifest,
        "counts": counts,
        "utc": spec.utc,
    }
    try:
        store.put_idempotent(
            commit_key, json.dumps(commit, sort_keys=True, indent=2).encode()
        )
    except DerivedConflict:
        forced_status = "blocked"
    manifest_key = f"{_attempt_prefix(spec.ctx)}/MANIFEST.json"
    write_manifest(store, manifest_key, manifest)
    if forced_status == "completed":
        _emit_pages(spec, store, ledger, manifest, counts, forced_status)
    status = forced_status
    return MaterializationResult(
        status=status,
        snapshot_id=snapshot_id,
        commit_key=commit_key,
        manifest=manifest,
        table_counts=counts,
        errors=acc.errors,
        checkpoint_uri=checkpoint_uri,
        completed_shards=sorted(completed),
    )


_PAGE_MAX_BYTES = 1_048_576  # readback index_page_bytes cap


def _emit_pages(
    spec: MaterializeSpec,
    store,
    ledger: BudgetLedger,
    manifest: list[dict],
    counts: dict[str, int],
    status: str,
) -> None:
    """Bounded unique-named <=1MiB JSONL pages + collector manifest.

    Re-chunks the ``first_paper_vectors`` shard partitions into page
    objects under ``pages/`` so the return path's bounded collector
    (``files_per_collect``/``total_bytes_per_collect`` caps) fetches a
    page set rather than every materialization partition. Also writes
    the authoritative ``status.json`` and ``asset_index.json`` at the
    attempt root.
    """
    if "first_paper_vectors" not in counts:
        return
    attempt = _attempt_prefix(spec.ctx)
    page_entries: list[dict] = []
    buf: list[bytes] = []
    buf_bytes = 0
    seq = 0

    def _flush() -> None:
        nonlocal buf, buf_bytes, seq
        if not buf:
            return
        seq += 1
        body = b"".join(buf)
        key = (
            f"{attempt}/pages/first_paper_vectors/page-{seq:05d}.jsonl"
        )
        store.put_idempotent(key, body)
        ledger.charge("max_api_calls_total", 1, "page put")
        ledger.charge("max_output_bytes", len(body), key)
        page_entries.append(
            {
                "page_id": f"page-{seq:05d}",
                "uri": key,
                "sha256": sha256_hex(body),
                "rows": buf_bytes and len(buf) or 0,
                "bytes": len(body),
            }
        )
        buf, buf_bytes = [], 0

    for e in manifest:
        if e.get("table_name") != "first_paper_vectors":
            continue
        body = store.get(e["uri"])
        ledger.charge("max_api_calls_total", 1, "page source read")
        for line in body.splitlines(keepends=True):
            if buf_bytes + len(line) > _PAGE_MAX_BYTES and buf:
                _flush()
            buf.append(line)
            buf_bytes += len(line)
    _flush()

    manifest_body = json.dumps(
        {
            "kind": "first_paper_pages_manifest",
            "reduction_id": spec.ctx.reduction_id,
            "table_name": "first_paper_vectors",
            "entries": page_entries,
            "page_count": len(page_entries),
            "rows": sum(p["rows"] for p in page_entries),
            "bytes": sum(p["bytes"] for p in page_entries),
        },
        sort_keys=True,
        indent=2,
    ).encode()
    manifest_key = (
        f"{attempt}/pages/first_paper_vectors.pages_manifest.json"
    )
    store.put_idempotent(manifest_key, manifest_body)
    ledger.charge("max_api_calls_total", 1, "pages manifest put")
    ledger.charge("max_output_bytes", len(manifest_body), manifest_key)

    status_key = f"{attempt}/status.json"
    status_body = json.dumps(
        {
            "kind": "reduction_attempt_status",
            "reduction_id": spec.ctx.reduction_id,
            "status": status,
            "counts": counts,
            "pages_manifest_key": manifest_key,
            "utc": spec.utc,
        },
        sort_keys=True,
        indent=2,
    ).encode()
    store.put_idempotent(status_key, status_body)
    ledger.charge("max_api_calls_total", 1, "status put")
    ledger.charge("max_output_bytes", len(status_body), status_key)

    index_body = json.dumps(
        {
            "kind": "reduction_asset_index",
            "reduction_id": spec.ctx.reduction_id,
            "assets": [
                {
                    "kind": "pages_manifest",
                    "uri": manifest_key,
                    "sha256": sha256_hex(manifest_body),
                    "bytes": len(manifest_body),
                },
                {
                    "kind": "status",
                    "uri": status_key,
                    "sha256": sha256_hex(status_body),
                    "bytes": len(status_body),
                },
            ]
            + [
                {**p, "kind": "vector_page"} for p in page_entries
            ],
        },
        sort_keys=True,
        indent=2,
    ).encode()
    store.put_idempotent(f"{attempt}/asset_index.json", index_body)
    ledger.charge("max_api_calls_total", 1, "asset index put")
    ledger.charge("max_output_bytes", len(index_body), "asset index")


def _derived_rows(
    spec: MaterializeSpec,
    acc: _ShardAccumulator,
    manifest: list[dict],
    status: str,
) -> dict[str, list[dict]]:
    """Post-shard base rows: coverage, weights, distributions, attempt."""
    tables: dict[str, list[dict]] = {}
    cell_rows = coverage_cell_rows(acc.cells, spec.ctx)
    tables["coverage_cells"] = cell_rows
    if "weights" not in spec.suppress_tables:
        tables["weights"] = weights_rows(
            sorted(acc.selected_runs), spec.ctx)
    if "distributions" not in spec.suppress_tables:
        tables["distributions"] = distribution_rows(
            acc.metric_values, acc.run_meta, spec.ctx
        )
    snapshot_id = f"snap-{sha256_hex(canonical_json(manifest).encode())[:16]}"
    tables["catalog_partitions"] = [
        catalog_partition_row(e, spec.ctx, snapshot_id)
        for e in manifest
        if "table_name" in e
    ]
    tables["reduction_attempts"] = [
        reduction_attempt_row(
            spec.ctx,
            status,
            {"spent": {}},
            {"cells": len(acc.cells)},
            None,
            spec.utc,
            spec.utc,
        )
    ]
    return tables
